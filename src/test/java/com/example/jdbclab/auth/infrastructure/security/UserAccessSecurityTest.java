package com.example.jdbclab.auth.infrastructure.security;

import com.example.jdbclab.auth.application.TokenIssuer;
import com.example.jdbclab.infrastructure.JdbcLabApplication;
import com.jayway.jsonpath.JsonPath;
import com.nimbusds.jose.jwk.source.ImmutableSecret;
import jakarta.servlet.Filter;
import java.security.SecureRandom;
import java.time.Instant;
import java.util.Base64;
import javax.crypto.SecretKey;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.security.oauth2.jose.jws.MacAlgorithm;
import org.springframework.security.oauth2.jwt.*;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.web.context.WebApplicationContext;

import static org.hamcrest.Matchers.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

/** Uses real Bearer headers, the production filter chain and decoder, and isolated H2. */
@SpringBootTest(classes = JdbcLabApplication.class, properties = {
        "spring.profiles.active=", "app.dev-db-reset=false", "auth.jwt.issuer=access-test",
        "spring.datasource.url=jdbc:h2:mem:jwtaccess;DB_CLOSE_DELAY=-1",
        "spring.datasource.username=sa", "spring.datasource.password=",
        "spring.datasource.driver-class-name=org.h2.Driver"})
class UserAccessSecurityTest {
    private static final String KEY = randomSecret();
    @DynamicPropertySource
    static void signing(DynamicPropertyRegistry properties) { properties.add("auth.jwt.secret", () -> KEY); }
    private static String randomSecret() {
        // 64 bytes also allow a correctly signed HS512 token to test strict HS256 pinning.
        byte[] bytes = new byte[64];
        new SecureRandom().nextBytes(bytes);
        return Base64.getEncoder().encodeToString(bytes);
    }

    @Autowired WebApplicationContext context;
    @Autowired JdbcTemplate jdbc;
    @Autowired TokenIssuer tokens;
    @Autowired PasswordEncoder passwords;
    @Autowired SecretKey jwtSigningKey;
    private MockMvc mvc;

    @BeforeEach
    void setUp() {
        mvc = MockMvcBuilders.webAppContextSetup(context)
                .addFilters(context.getBean("springSecurityFilterChain", Filter.class)).build();
        jdbc.execute("DROP TABLE IF EXISTS users");
        jdbc.execute("""
                CREATE TABLE users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                    name VARCHAR(50) NOT NULL, lastname VARCHAR(50) NOT NULL,
                    email VARCHAR(254) UNIQUE NOT NULL, password_hash VARCHAR(512) NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL)
                """);
        for (int id : new int[]{1, 2}) {
            jdbc.update("INSERT INTO users (id, name, lastname, email, password_hash) VALUES (?, ?, ?, ?, ?)",
                    id, "User", "Example", "user" + id + "@example.test", passwords.encode("login-test-password"));
        }
    }

    private String signed(JwtClaimsSet claims, MacAlgorithm algorithm) {
        return new NimbusJwtEncoder(new ImmutableSecret<>(jwtSigningKey))
                .encode(JwtEncoderParameters.from(JwsHeader.with(algorithm).build(), claims)).getTokenValue();
    }

    private JwtClaimsSet.Builder claims() {
        return JwtClaimsSet.builder().subject("1").issuer("access-test")
                .issuedAt(Instant.now().minusSeconds(600)).expiresAt(Instant.now().plusSeconds(600));
    }

    private void unauthorized(String authorization) throws Exception {
        for (String path : new String[]{"/users", "/users/2"}) {
            var request = get(path);
            if (authorization != null) request.header("Authorization", authorization);
            mvc.perform(request).andExpect(status().isUnauthorized())
                    .andExpect(header().string("WWW-Authenticate", "Bearer"))
                    .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON))
                    .andExpect(jsonPath("$.detail").value("A valid Bearer token is required."))
                    .andExpect(jsonPath("$.status").value(401));
        }
    }

    @Test
    void missingAndMalformedBearerHeadersReturn401() throws Exception {
        for (String header : new String[]{null, "Basic dXNlcjpwYXNz", "Bearer", "Bearer ",
                "Bearer not-a-jwt", "Bearer invalid token"}) unauthorized(header);
    }

    @Test
    void tamperedAndWronglySignedTokensReturn401() throws Exception {
        String valid = tokens.issue(1L).value();
        int signature = valid.lastIndexOf('.') + 1;
        String tampered = valid.substring(0, signature) + (valid.charAt(signature) == 'A' ? 'B' : 'A')
                + valid.substring(signature + 1);
        unauthorized("Bearer " + tampered);
        var otherKey = new javax.crypto.spec.SecretKeySpec(Base64.getDecoder().decode(randomSecret()), "HmacSHA256");
        String wrongKey = new NimbusJwtEncoder(new ImmutableSecret<>(otherKey))
                .encode(JwtEncoderParameters.from(JwsHeader.with(MacAlgorithm.HS256).build(), claims().build()))
                .getTokenValue();
        unauthorized("Bearer " + wrongKey);
    }

    @Test
    void expiredWrongIssuerAndWrongAlgorithmTokensReturn401() throws Exception {
        unauthorized("Bearer " + signed(claims().expiresAt(Instant.now().minusSeconds(1)).build(), MacAlgorithm.HS256));
        unauthorized("Bearer " + signed(claims().issuer("another-issuer").build(), MacAlgorithm.HS256));
        unauthorized("Bearer " + signed(claims().build(), MacAlgorithm.HS512));
    }

    @Test
    void missingExpirationMissingSubjectAndFutureNotBeforeReturn401() throws Exception {
        unauthorized("Bearer " + signed(JwtClaimsSet.builder().subject("1").issuer("access-test")
                .issuedAt(Instant.now()).build(), MacAlgorithm.HS256));
        unauthorized("Bearer " + signed(JwtClaimsSet.builder().issuer("access-test").issuedAt(Instant.now())
                .expiresAt(Instant.now().plusSeconds(600)).build(), MacAlgorithm.HS256));
        unauthorized("Bearer " + signed(claims().notBefore(Instant.now().plusSeconds(60)).build(), MacAlgorithm.HS256));
    }

    @Test
    void validTokenAllowsListingAndReadingAnotherUserWithoutExposingHashes() throws Exception {
        String header = "Bearer " + tokens.issue(1L).value();
        mvc.perform(get("/users").header("Authorization", header))
                .andExpect(status().isOk()).andExpect(jsonPath("$.length()").value(2))
                .andExpect(jsonPath("$[0].id").value(1)).andExpect(jsonPath("$[1].id").value(2))
                .andExpect(jsonPath("$[0].length()").value(6))
                .andExpect(content().string(not(containsString("password"))))
                .andExpect(header().doesNotExist("Set-Cookie"));
        mvc.perform(get("/users/2").header("Authorization", header))
                .andExpect(status().isOk()).andExpect(jsonPath("$.id").value(2))
                .andExpect(jsonPath("$.length()").value(6))
                .andExpect(content().string(not(containsString("password"))));
    }

    @Test
    void authenticatedMissingUserIs404AndInvalidIdStill400() throws Exception {
        String header = "Bearer " + tokens.issue(1L).value();
        mvc.perform(get("/users/999").header("Authorization", header))
                .andExpect(status().isNotFound()).andExpect(jsonPath("$.status").value(404));
        mvc.perform(get("/users/not-an-id").header("Authorization", header))
                .andExpect(status().isBadRequest());
        mvc.perform(get("/users/999")).andExpect(status().isUnauthorized());
        mvc.perform(head("/users/2")).andExpect(status().isUnauthorized());
        mvc.perform(head("/users/2").header("Authorization", header)).andExpect(status().isOk());
    }

    @Test
    void loginAndRegistrationRemainPublicAndLoginTokenCanAccessUsers() throws Exception {
        var result = mvc.perform(post("/auth/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"user1@example.test\",\"password\":\"login-test-password\"}"))
                .andExpect(status().isOk()).andReturn();
        String token = JsonPath.read(result.getResponse().getContentAsString(), "$.accessToken");
        mvc.perform(get("/users/2").header("Authorization", "Bearer " + token)).andExpect(status().isOk());
        mvc.perform(post("/auth/register").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"New\",\"lastname\":\"User\",\"email\":\"new@example.test\",\"password\":\"new-test-password\"}"))
                .andExpect(status().isCreated()).andExpect(jsonPath("$.accessToken").doesNotExist());
    }

    @Test
    void tokenQueryParameterDoesNotAuthenticateAndContextPathsAreProtected() throws Exception {
        String token = tokens.issue(1L).value();
        mvc.perform(get("/users").param("access_token", token)).andExpect(status().isUnauthorized());
        mvc.perform(get("/jdbc/users").contextPath("/jdbc")).andExpect(status().isUnauthorized());
        mvc.perform(get("/jdbc/users/2").contextPath("/jdbc").header("Authorization", "Bearer " + token))
                .andExpect(status().isOk());
    }
}
