-- Executed by setup.py with a password bind supplied through standard input.
-- Never put credentials in this file. FREEPDB1 must already exist.
SET ECHO OFF
SET VERIFY OFF
SET SERVEROUTPUT ON
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
ALTER SESSION SET CONTAINER = FREEPDB1;

DECLARE
    user_count PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO user_count FROM DBA_USERS WHERE USERNAME = 'STORE_JDBC';
    IF user_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER store_jdbc IDENTIFIED BY '
            || DBMS_ASSERT.ENQUOTE_NAME(:setup_password, FALSE)
            || ' DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP';
        DBMS_OUTPUT.PUT_LINE('Created STORE_JDBC.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('STORE_JDBC already exists; password and data preserved.');
    END IF;
END;
/

-- Explicit development privileges; no DBA or broad developer role.
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO store_jdbc;
ALTER USER store_jdbc QUOTA 100M ON USERS;

SELECT USERNAME, ACCOUNT_STATUS, DEFAULT_TABLESPACE
FROM DBA_USERS WHERE USERNAME = 'STORE_JDBC';
SELECT PRIVILEGE FROM DBA_SYS_PRIVS WHERE GRANTEE = 'STORE_JDBC' ORDER BY PRIVILEGE;
SELECT TABLESPACE_NAME, MAX_BYTES FROM DBA_TS_QUOTAS WHERE USERNAME = 'STORE_JDBC';
EXIT SUCCESS
